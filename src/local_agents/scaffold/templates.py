TOOLS_PY = '''"""Custom tools for the {name} agent.

A tool is a class with a ``name``, ``description``, ``parameters`` and an async
``execute``. See the local-agents README for details.
"""

from __future__ import annotations

from datetime import datetime, timezone

from local_agents import BaseTool, ToolParameter


class {tool_class_name}(BaseTool):
    """Return the current date and time. Replace with something useful."""

    name = "current_time"
    description = "Get the current date and time, optionally in UTC."
    parameters = (
        ToolParameter(
            "utc", "boolean", "Return UTC instead of local time", required=False, default=False
        ),
    )

    async def execute(self, utc: bool = False) -> str:
        now = datetime.now(timezone.utc) if utc else datetime.now().astimezone()
        return now.strftime("%Y-%m-%d %H:%M:%S %Z")
'''

