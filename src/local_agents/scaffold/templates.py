TEST_PY = '''"""Tests for the {name} agent. They use a scripted model, so no Ollama is needed."""

from __future__ import annotations

import asyncio
from pathlib import Path

import pytest

from local_agents import AgentRegistry
from local_agents.testing import ScriptedModel, ScriptedTurn

AGENT_FILE = Path(__file__).resolve().parent.parent / "agent.py"


@pytest.fixture
def agent_cls():
    registry = AgentRegistry()
    registry.load_file(AGENT_FILE)
    return registry.get("{name}")


def test_agent_is_registered(agent_cls) -> None:
    assert agent_cls.name == "{name}"
    assert agent_cls.description


def test_agent_answers(agent_cls) -> None:
    model = ScriptedModel(["Hello from {name}!"])
    agent = agent_cls(model=model, tools=agent_cls.custom_tools())
    result = asyncio.run(agent.run("Say hello"))
    assert result.output == "Hello from {name}!"
    assert result.stop_reason == "final"


def test_agent_uses_custom_tool(agent_cls) -> None:
    model = ScriptedModel(
        [
            ScriptedTurn.call("current_time", utc=True),
            "The time was reported above.",
        ]
    )
    agent = agent_cls(model=model, tools=agent_cls.custom_tools())
    result = asyncio.run(agent.run("What time is it?"))
    assert result.tool_calls and result.tool_calls[0].name == "current_time"
    assert result.tool_calls[0].result.success
    assert result.output == "The time was reported above."
'''

